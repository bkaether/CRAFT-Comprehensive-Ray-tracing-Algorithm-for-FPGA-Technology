#!/usr/bin/env python3
"""
Generate norm_lut.mem for generate_ray_norm.sv and report the datapath's accuracy.

Table: 512 entries, address = s_trimmed[21:13] (s in Q2.20, so address i covers s = i/128).
Each entry is 25 bits = {value Q1.16 (17 bits), difference to next entry (8 bits, in 2^-16 LSBs)}.
  value[i] = round(1/sqrt(i/128) * 2^16)
  diff[i]  = value[i] - value[i+1]      (computed from the ROUNDED values, so interpolation
                                         lands exactly on the next stored entry)
Addresses 0-127 (s < 1) never occur; they are filled with the s = 1 entry and diff 0.

The script also contains a bit-accurate model of the generate_ray_norm datapath and sweeps it
over the camera-space input range, comparing against ideal floating-point normalization.

Usage:
  python gen_norm_lut.py                 # writes <repo root>/rtl/mem/norm_lut.mem, prints report
  python gen_norm_lut.py -o path/to.mem  # custom output path
  python gen_norm_lut.py --no-sweep      # table only

The repo root is found by walking up from this script's folder until a .git directory is found,
so the script works from any working directory and from anywhere inside the repo.
"""
import argparse
import math
import os
import random

# ---------------------------------------------------------------------------
# Format constants (must match generate_ray_norm.sv)
# ---------------------------------------------------------------------------
ADDR_BITS = 9                    # lut_addr = s_trimmed[21:13]
ENTRIES = 1 << ADDR_BITS         # 512
S_INT_BITS = 2                   # s_trimmed is Q2.20
S_FRAC_BITS = 20
ADDR_FRAC_BITS = ADDR_BITS - S_INT_BITS          # 7 -> spacing 1/128
INTERP_BITS = S_FRAC_BITS - ADDR_FRAC_BITS       # 13 leftover bits used for interpolation
VAL_FRAC = 16                    # table values are Q1.16
VAL_BITS = 17
DIFF_BITS = 8
S_MIN_ADDR = 1 << ADDR_FRAC_BITS                 # address of s = 1.0 (128)

# Camera-space range for 70 deg vertical FOV, 4:3 (matches generate_ray)
FOV_DEG = 70.0
ASPECT = 4.0 / 3.0
SENSOR_H = 2.0 * math.tan(math.radians(FOV_DEG) / 2.0)
SENSOR_W = ASPECT * SENSOR_H
X_MAX = SENSOR_W / 2.0
Y_MAX = SENSOR_H / 2.0

LSB = 2.0 ** -16                 # output LSB (SQ1.16)

# Output location, relative to the repo root
MEM_REL_PATH = os.path.join("rtl", "mem", "norm_lut.mem")


def find_repo_root():
    """Walk up from this script's folder until a folder containing .git is found."""
    d = os.path.dirname(os.path.abspath(__file__))
    while True:
        if os.path.exists(os.path.join(d, ".git")):
            return d
        parent = os.path.dirname(d)
        if parent == d:
            raise SystemExit("error: could not find the repo root (no .git above this script); "
                             "pass an explicit output path with -o")
        d = parent


# ---------------------------------------------------------------------------
# Table generation
# ---------------------------------------------------------------------------
def ideal_value(addr):
    """Stored Q1.16 value for an address, as an integer."""
    s = addr / float(1 << ADDR_FRAC_BITS)
    return int(round((1.0 / math.sqrt(s)) * (1 << VAL_FRAC)))


def build_table():
    values = [0] * ENTRIES
    diffs = [0] * ENTRIES
    for a in range(S_MIN_ADDR, ENTRIES):
        values[a] = ideal_value(a)
    # next value after the last entry is s = 4.0 -> 0.5 exactly
    next_after_last = ideal_value(ENTRIES)
    for a in range(S_MIN_ADDR, ENTRIES):
        nxt = values[a + 1] if a + 1 < ENTRIES else next_after_last
        diffs[a] = values[a] - nxt
    # unused addresses (s < 1): repeat the s = 1 entry, no slope
    for a in range(S_MIN_ADDR):
        values[a] = values[S_MIN_ADDR]
        diffs[a] = 0

    # width checks
    for a in range(ENTRIES):
        assert 0 <= values[a] < (1 << VAL_BITS), f"value overflow at addr {a}: {values[a]}"
        assert 0 <= diffs[a] < (1 << DIFF_BITS), (
            f"difference at addr {a} is {diffs[a]}, does not fit in {DIFF_BITS} bits")
    return values, diffs


def write_mem(path, values, diffs):
    width_hex = (VAL_BITS + DIFF_BITS + 3) // 4
    with open(path, "w") as f:
        f.write("// norm_lut.mem - generated by gen_norm_lut.py, do not edit by hand\n")
        f.write(f"// {ENTRIES} entries, address = s_trimmed[21:13], spacing 1/{1 << ADDR_FRAC_BITS}\n")
        f.write("// entry = {1/sqrt(s) Q1.16 (17 bits), diff to next entry (8 bits, 2^-16 LSBs)}\n")
        f.write(f"// addresses 0-{S_MIN_ADDR - 1} (s < 1) unused: filled with the s = 1 entry, diff 0\n")
        for a in range(ENTRIES):
            word = (values[a] << DIFF_BITS) | diffs[a]
            f.write(f"{word:0{width_hex}X}\n")


# ---------------------------------------------------------------------------
# Bit-accurate model of generate_ray_norm.sv
# ---------------------------------------------------------------------------
def floor_shift(v, n):
    """Arithmetic right shift (= taking the upper bits of a two's complement value)."""
    return v >> n  # Python >> on ints is floor division by 2^n, matching bit slicing


def norm_model(x, y, values, diffs):
    """x, y: SQ2.16 integers. Returns (x_norm, y_norm, z_norm) as SQ1.16 integers, plus internals."""
    # stage 1: s = x^2 + y^2 + 1 (SQ5.32), trim to Q2.20 = s[33:12]
    s = x * x + y * y + (1 << 32)
    s_trimmed = (s >> 12) & ((1 << 22) - 1)

    # stage 2: lut read
    addr = s_trimmed >> INTERP_BITS
    frac = s_trimmed & ((1 << INTERP_BITS) - 1)
    entry = values[addr]
    diff = diffs[addr]

    # stage 3: interpolate. s_interp is {7'b0, frac} as Q0.20; interp_val = s_interp * (diff << 7) -> Q0.36
    interp_val = frac * (diff << ADDR_FRAC_BITS)
    norm_div = (entry << 20) - interp_val          # Q1.36
    norm_div_trimmed = norm_div >> 16              # [37:16] -> SQ1.20 (always positive)

    # stage 4: final multiply and trim
    x_full = x * norm_div_trimmed                  # SQ4.36
    y_full = y * norm_div_trimmed
    x_norm = floor_shift(x_full, 20)               # {[40], [36:20]} -> SQ1.16
    y_norm = floor_shift(y_full, 20)
    z_norm = floor_shift(-norm_div_trimmed, 4)     # [21:4] -> SQ1.16
    return x_norm, y_norm, z_norm, norm_div_trimmed, s_trimmed


def to_sq2_16(v):
    return int(math.floor(v * (1 << 16)))


def sweep(values, diffs, n_random=200_000, grid=257, seed=1):
    rng = random.Random(seed)
    pts = []
    for i in range(grid):
        for j in range(grid):
            pts.append((-X_MAX + 2 * X_MAX * i / (grid - 1), -Y_MAX + 2 * Y_MAX * j / (grid - 1)))
    for _ in range(n_random):
        pts.append((rng.uniform(-X_MAX, X_MAX), rng.uniform(-Y_MAX, Y_MAX)))
    pts += [(0.0, 0.0), (X_MAX, Y_MAX), (-X_MAX, -Y_MAX), (X_MAX, 0.0), (0.0, Y_MAX)]

    worst = {"x": (0.0, None), "y": (0.0, None), "z": (0.0, None), "r": (0.0, None), "len": (0.0, None)}
    sums = {"x": 0.0, "y": 0.0, "z": 0.0, "r": 0.0}
    s_max = 0.0
    for fx, fy in pts:
        xi, yi = to_sq2_16(fx), to_sq2_16(fy)
        xq, yq = xi / 65536.0, yi / 65536.0          # the exact value the hardware receives
        s_true = xq * xq + yq * yq + 1.0
        s_max = max(s_max, s_true)
        r_true = 1.0 / math.sqrt(s_true)

        xn, yn, zn, r_hw, _ = norm_model(xi, yi, values, diffs)
        errs = {
            "x": abs(xn * LSB - xq * r_true),
            "y": abs(yn * LSB - yq * r_true),
            "z": abs(zn * LSB - (-r_true)),
            "r": abs(r_hw * 2.0 ** -20 - r_true),
        }
        length_err = abs(math.sqrt((xn * LSB) ** 2 + (yn * LSB) ** 2 + (zn * LSB) ** 2) - 1.0)
        errs["len"] = length_err
        for k, e in errs.items():
            if e > worst[k][0]:
                worst[k] = (e, (fx, fy))
            if k in sums:
                sums[k] += e
    n = len(pts)
    return worst, {k: v / n for k, v in sums.items()}, n, s_max


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--output", default=None,
                    help=f"output path (default: <repo root>/{MEM_REL_PATH.replace(os.sep, '/')})")
    ap.add_argument("--no-sweep", action="store_true")
    args = ap.parse_args()

    if args.output is None:
        args.output = os.path.join(find_repo_root(), MEM_REL_PATH)
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)

    values, diffs = build_table()
    write_mem(args.output, values, diffs)

    used = range(S_MIN_ADDR, ENTRIES)
    print(f"wrote {args.output}")
    print(f"  entries: {ENTRIES}, used addresses {S_MIN_ADDR}-{ENTRIES - 1}")
    print(f"  value range: {min(values[a] for a in used)}..{max(values[a] for a in used)} "
          f"({min(values[a] for a in used) * LSB:.6f}..{max(values[a] for a in used) * LSB:.6f})")
    print(f"  max diff: {max(diffs)} LSBs (limit {(1 << DIFF_BITS) - 1}) at addr {diffs.index(max(diffs))}")

    # table-only interpolation error (ideal fraction, rounded table): checks the 2^-17 design claim
    worst_tab = 0.0
    for a in used:
        for k in range(0, 1 << INTERP_BITS, 64):
            t = k / float(1 << INTERP_BITS)
            s = (a + t) / float(1 << ADDR_FRAC_BITS)
            approx = (values[a] - t * diffs[a]) * LSB
            worst_tab = max(worst_tab, abs(approx - 1.0 / math.sqrt(s)))
    print(f"  table + interpolation error (ideal arithmetic): {worst_tab / LSB:.3f} LSB "
          f"(design target 0.5 LSB = 2^-17)")

    if args.no_sweep:
        return
    print(f"\nbit-accurate datapath sweep over camera space x in +-{X_MAX:.4f}, y in +-{Y_MAX:.4f}")
    worst, mean, n, s_max = sweep(values, diffs)
    print(f"  {n} points, max s seen = {s_max:.4f}")
    print(f"  {'output':<10}{'max err (LSB)':>15}{'mean err (LSB)':>16}   worst at (x, y)")
    for k, label in (("r", "1/sqrt(s)"), ("x", "x_norm"), ("y", "y_norm"), ("z", "z_norm")):
        e, where = worst[k]
        print(f"  {label:<10}{e / LSB:>15.3f}{mean[k] / LSB:>16.3f}   ({where[0]:+.4f}, {where[1]:+.4f})")
    e, where = worst["len"]
    print(f"  |dir| - 1 max: {e:.2e}  ({e / LSB:.2f} LSB)   at ({where[0]:+.4f}, {where[1]:+.4f})")


if __name__ == "__main__":
    main()
