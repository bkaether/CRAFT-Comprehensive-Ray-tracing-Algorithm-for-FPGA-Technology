#!/usr/bin/env python3
"""
Generate reciprocal_lut.mem for ray_dir_inverse.sv and report the datapath's accuracy.

Range reduction: |d| = m * 2^-k with m in [1, 2), so 1/|d| = (1/m) * 2^k.
Table: 256 entries over m in [1, 2), spacing 1/256, address = m[15:8] (m is Q1.16, bit 16 always 1).
Each entry is 25 bits = {value Q1.16 (17 bits), difference to next entry (8 bits, in 2^-16 LSBs)}.
  value[i] = round(2^16 / (1 + i/256))
  diff[i]  = value[i] - value[i+1]     (from the ROUNDED values; value[256] = 1/2 exactly)

The script also contains a bit-accurate model of the ray_dir_inverse datapath (abs, leading-zero
count, shift, table read, interpolation, trim) and checks it exhaustively against exact 1/|d| for
every nonzero Q1.16 magnitude a unit-vector component can have (1 .. 2^16).

Usage:
  python gen_reciprocal_lut.py                 # writes <repo root>/rtl/mem/reciprocal_lut.mem, prints report
  python gen_reciprocal_lut.py -o path/to.mem  # custom output path
  python gen_reciprocal_lut.py --no-sweep      # table only

The repo root is found by walking up from this script's folder until a .git directory is found.
"""
import argparse
import os

# ---------------------------------------------------------------------------
# Format constants (must match ray_dir_inverse.sv)
# ---------------------------------------------------------------------------
ABS_BITS = 17                    # |d| and m are Q1.16 (17 bits)
FRAC = 16                        # fractional bits of |d|, m, and the table values
ADDR_BITS = 8                    # addr = m[15:8]
ENTRIES = 1 << ADDR_BITS         # 256
REM_BITS = FRAC - ADDR_BITS      # 8 remainder bits, m[7:0]
VAL_BITS = 17                    # table values are Q1.16
DIFF_BITS = 8
ONE = 1 << FRAC                  # 1.0 in Q1.16

MEM_REL_PATH = os.path.join("rtl", "mem", "reciprocal_lut.mem")


def find_repo_root():
    """Walk up from this script's folder until a folder containing .git is found."""
    d = os.path.dirname(os.path.abspath(__file__))
    while True:
        if os.path.exists(os.path.join(d, ".git")):
            return d
        parent = os.path.dirname(d)
        if parent == d:
            raise SystemExit("error: could not find the repo root (no .git above this script); "
                             "pass an explicit output path with -o")
        d = parent


# ---------------------------------------------------------------------------
# Table generation
# ---------------------------------------------------------------------------
def ideal_value(i):
    """Stored Q1.16 value of 1/m at m = 1 + i/256, as an integer (round half up, exact integer math)."""
    # 2^16 / (1 + i/256) = 2^24 / (256 + i); round to nearest
    num = 1 << (FRAC + ADDR_BITS)
    den = ENTRIES + i
    return (2 * num + den) // (2 * den)


def build_table():
    values = [ideal_value(i) for i in range(ENTRIES + 1)]    # values[256] = 1/2 (next after last)
    diffs = [values[i] - values[i + 1] for i in range(ENTRIES)]
    values = values[:ENTRIES]
    for i in range(ENTRIES):
        assert 0 < values[i] < (1 << VAL_BITS), f"value overflow at addr {i}: {values[i]}"
        assert 0 <= diffs[i] < (1 << DIFF_BITS), (
            f"difference at addr {i} is {diffs[i]}, does not fit in {DIFF_BITS} bits")
    return values, diffs


def write_mem(path, values, diffs):
    width_hex = (VAL_BITS + DIFF_BITS + 3) // 4
    with open(path, "w") as f:
        f.write("// reciprocal_lut.mem - generated by gen_reciprocal_lut.py, do not edit by hand\n")
        f.write(f"// {ENTRIES} entries, address = m[15:8] (m in [1, 2), Q1.16), spacing 1/{ENTRIES}\n")
        f.write("// entry = {1/m Q1.16 (17 bits), diff to next entry (8 bits, 2^-16 LSBs)}\n")
        for i in range(ENTRIES):
            f.write(f"{(values[i] << DIFF_BITS) | diffs[i]:0{width_hex}X}\n")


# ---------------------------------------------------------------------------
# Bit-accurate model of ray_dir_inverse.sv (one component)
# ---------------------------------------------------------------------------
def leading_zero_count(v, width=ABS_BITS):
    for i in range(width - 1, -1, -1):
        if (v >> i) & 1:
            return width - 1 - i
    return width


def inverse_model(d, values, diffs):
    """d: SQ1.16 integer. Returns (mantissa Q1.16 int, sign, shift k, div_by_zero)."""
    sign = 1 if d < 0 else 0
    abs_d = (-d if sign else d) & ((1 << ABS_BITS) - 1)        # trimmed to Q1.16
    k = leading_zero_count(abs_d)
    div_by_zero = (k == ABS_BITS)
    m = (abs_d << k) & ((1 << ABS_BITS) - 1)
    addr = (m >> REM_BITS) & (ENTRIES - 1)                     # m[15:8]
    rem = m & ((1 << REM_BITS) - 1)                            # m[7:0], read as Q0.16
    entry, diff = values[addr], diffs[addr]
    mult = (diff << ADDR_BITS) * rem                           # Q0.32 (<< 8 is the divide by spacing)
    inv = ((entry << FRAC) | (1 << (FRAC - 1))) - mult         # Q1.32, padding 16'h8000 = +half LSB
    mantissa = inv >> FRAC                                     # trim to Q1.16 (rounds, thanks to the half LSB)
    return mantissa, sign, k, div_by_zero


def sweep(values, diffs):
    """Exhaustive over every nonzero magnitude 1 .. 2^16 (both signs give the same magnitude path)."""
    worst_mant = (0.0, None)
    worst_rel = (0.0, None)
    sum_mant = 0.0
    n = 0
    for a in range(1, ONE + 1):
        for d in (a, -a):
            mant, sign, k, dbz = inverse_model(d, values, diffs)
            assert not dbz, f"unexpected div_by_zero for d={d}"
            assert sign == (d < 0)
            # m as a real number in [1, 2), and the exact 1/m it should approximate
            m_real = ((a << k) & ((1 << ABS_BITS) - 1)) / ONE
            exact_mant = 1.0 / m_real
            err_lsb = abs(mant / ONE - exact_mant) * ONE
            # full reconstructed 1/|d| vs exact, as relative error
            recon = (mant / ONE) * (2.0 ** k)
            exact = ONE / a
            rel = abs(recon - exact) / exact
            if err_lsb > worst_mant[0]:
                worst_mant = (err_lsb, d)
            if rel > worst_rel[0]:
                worst_rel = (rel, d)
            sum_mant += err_lsb
            n += 1
    # zero must flag div_by_zero
    _, _, k0, dbz0 = inverse_model(0, values, diffs)
    assert dbz0 and k0 == ABS_BITS, "d = 0 must give shift = 17 and div_by_zero"
    return worst_mant, worst_rel, sum_mant / n, n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--output", default=None,
                    help=f"output path (default: <repo root>/{MEM_REL_PATH.replace(os.sep, '/')})")
    ap.add_argument("--no-sweep", action="store_true")
    args = ap.parse_args()

    if args.output is None:
        args.output = os.path.join(find_repo_root(), MEM_REL_PATH)
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)

    values, diffs = build_table()
    write_mem(args.output, values, diffs)

    print(f"wrote {args.output}")
    print(f"  entries: {ENTRIES}, value range {min(values)}..{max(values)} "
          f"({min(values) / ONE:.6f}..{max(values) / ONE:.6f})")
    print(f"  max diff: {max(diffs)} LSBs (limit {(1 << DIFF_BITS) - 1}) at addr {diffs.index(max(diffs))}")

    if args.no_sweep:
        return
    print("\nexhaustive bit-accurate sweep over every nonzero SQ1.16 magnitude (both signs)")
    (wm, dm), (wr, dr), mean_m, n = sweep(values, diffs)
    print(f"  {n} inputs")
    print(f"  mantissa (1/m) error: max {wm:.3f} LSB at d = {dm} ({dm / ONE:+.6f}), mean {mean_m:.3f} LSB")
    print(f"  reconstructed 1/|d| relative error: max {wr:.2e} (~{wr * ONE:.2f} mantissa LSB) at d = {dr}")
    print("  d = 0 -> shift 17, div_by_zero set: OK")


if __name__ == "__main__":
    main()
